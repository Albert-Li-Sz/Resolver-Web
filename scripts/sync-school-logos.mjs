import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const SOURCE = 'https://avatar.hydrooj.com/';

// Read Astro's serialized public catalog as data; never execute the page scripts.
export function parseSchoolLogoRegistry(html) {
  const island = html.match(/<astro-island\b[^>]*component-url="[^"]*LogoRegistry[^\"]*"[^>]*\bprops="([^"]*)"/i);
  if (!island) throw new Error('Hydro 学校 Logo 索引格式已变化，保留现有索引');
  const props = island[1].replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'")
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
  const rows = JSON.parse(props).logos?.[1];
  if (!Array.isArray(rows) || !rows.length) throw new Error('学校 Logo 索引为空');
  return rows.map(([, row]) => {
    const name = row.name?.[1];
    const aliases = row.aliases?.[1]?.map(([, value]) => value);
    const src = row.src?.[1];
    if (typeof name !== 'string' || !Array.isArray(aliases) || aliases.some((value) => typeof value !== 'string') ||
        typeof src !== 'string' || !/^\/org\/[^/?]+\.webp(?:\?build=[a-f0-9]+)?$/.test(src)) {
      throw new Error('学校 Logo 索引包含无效记录，保留现有索引');
    }
    return { name, aliases, src };
  });
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const response = process.argv[2] ? null : await fetch(SOURCE, { signal: AbortSignal.timeout(25_000) });
  if (response && !response.ok) throw new Error(`Hydro Logo 服务返回 HTTP ${response.status}`);
  const html = response ? await response.text() : await readFile(process.argv[2], 'utf8');
  if (Buffer.byteLength(html) > 5 * 1024 * 1024) throw new Error('学校 Logo 索引响应过大');
  const catalog = parseSchoolLogoRegistry(html);
  const output = `// Generated by npm run logos:sync from ${SOURCE}\n` +
    '// School names, aliases and logo paths are provided by the Hydro logo registry.\n' +
    `export const SCHOOL_LOGOS = [\n${catalog.map((row) => `  ${JSON.stringify(row)},`).join('\n')}\n];\n`;
  await writeFile(new URL('../public/js/school-logo-catalog.js', import.meta.url), output);
  console.log(`Updated ${catalog.length} school logos from ${SOURCE}`);
}
